import re
from difflib import SequenceMatcher

import pandas as pd


def safe_text(value):

    if value is None or pd.isna(value):
        return ""

    return str(value).strip()


def contains_hangul(text):

    return bool(
        re.search(
            r"[가-힣]",
            safe_text(text),
        )
    )


def contains_latin(text):

    return bool(
        re.search(
            r"[A-Z]",
            safe_text(text).upper(),
        )
    )


def name_similarity(a, b):

    a = safe_text(a)
    b = safe_text(b)

    if not a or not b:
        return 0.0

    return SequenceMatcher(
        None,
        a,
        b,
        autojunk=False,
    ).ratio()


def rule_applies(
    train_name,
    position,
    hangul_part,
):

    train_name = safe_text(
        train_name
    )

    if position == "PREFIX":

        return train_name.startswith(
            hangul_part
        )

    if position == "SUFFIX":

        return train_name.endswith(
            hangul_part
        )

    raise ValueError(position)


def candidate_rule_match(
    catalog_name,
    position,
    latin_part,
):

    catalog_name = safe_text(
        catalog_name
    )

    if position == "PREFIX":

        return catalog_name.startswith(
            latin_part
        )

    if position == "SUFFIX":

        return catalog_name.endswith(
            latin_part
        )

    raise ValueError(position)


def build_kl_features(
    train_name,
    catalog_name,
    rules,
):

    train_name = safe_text(
        train_name
    )

    catalog_name = safe_text(
        catalog_name
    )

    if not contains_hangul(
        train_name
    ):
        return 0, 0

    if not contains_latin(
        catalog_name
    ):
        return 0, 0

    selected = []

    for position in [
        "PREFIX",
        "SUFFIX",
    ]:

        applicable = []

        for rule in rules:

            if (
                rule["position"]
                != position
            ):
                continue

            if rule_applies(
                train_name,
                position,
                rule["hangul_part"],
            ):

                applicable.append(
                    rule
                )

        if not applicable:
            continue

        applicable = sorted(
            applicable,
            key=lambda x: (
                -len(
                    x["hangul_part"]
                ),
                x["rule_id"],
            ),
        )

        selected.append(
            applicable[0]
        )

    available = int(
        len(selected) > 0
    )

    match = int(
        any(
            candidate_rule_match(
                catalog_name,
                rule["position"],
                rule["latin_part"],
            )
            for rule
            in selected
        )
    )

    return available, match


def add_m6_features(
    df,
    rules,
):

    df = df.copy()

    unique_pairs = (
        df[
            [
                "train_name_normalized",
                "catalog_name_normalized",
            ]
        ]
        .drop_duplicates()
        .reset_index(drop=True)
    )

    unique_pairs[
        "name_similarity"
    ] = [
        name_similarity(a, b)
        for a, b
        in zip(
            unique_pairs[
                "train_name_normalized"
            ],
            unique_pairs[
                "catalog_name_normalized"
            ],
        )
    ]

    kl_available = []
    kl_match = []

    for row in unique_pairs.itertuples(
        index=False
    ):

        available, match = (
            build_kl_features(
                row.train_name_normalized,
                row.catalog_name_normalized,
                rules,
            )
        )

        kl_available.append(
            available
        )

        kl_match.append(
            match
        )

    unique_pairs[
        "korean_latin_rule_available"
    ] = kl_available

    unique_pairs[
        "korean_latin_rule_match"
    ] = kl_match

    df = df.merge(
        unique_pairs,
        on=[
            "train_name_normalized",
            "catalog_name_normalized",
        ],
        how="left",
        validate="many_to_one",
    )

    exact_from_similarity = (
        (
            df[
                "name_similarity"
            ]
            == 1.0
        )
        &
        (
            df[
                "name_missing"
            ]
            == 0
        )
    ).astype(int)

    mismatch = int(
        (
            exact_from_similarity
            != df[
                "name_normalized_exact"
            ].astype(int)
        ).sum()
    )

    if mismatch != 0:

        raise AssertionError(
            "name_similarity reconstruction "
            f"mismatch: {mismatch}"
        )

    if (
        df[
            "korean_latin_rule_match"
        ]
        >
        df[
            "korean_latin_rule_available"
        ]
    ).any():

        raise AssertionError(
            "KL match=1 while available=0"
        )

    return df
